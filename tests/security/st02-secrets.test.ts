import { execFile } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

import { describe, expect, it } from 'vitest';
import {
  findEnvExamples,
  findNonPlaceholderValues,
  findTrackedEnvFiles,
  MAX_PLACEHOLDER_SUFFIX,
} from './lib/secrets-policy.js';

const run = promisify(execFile);
const REPO_ROOT = fileURLToPath(new URL('../../', import.meta.url));

/**
 * Fixture values are obviously fake and low-entropy, or built at runtime, so
 * gitleaks never sees a token-shaped literal in this file.
 */
/** Long enough to look like a 32-character hex token. */
const HEX_GROUPS = 8;
const FAKE_HEX_SECRET = 'ab12'.repeat(HEX_GROUPS);

async function listTrackedFiles(): Promise<readonly string[]> {
  const { stdout } = await run('git', ['ls-files', '-z'], { cwd: REPO_ROOT });
  return stdout.split('\0').filter((path) => path.length > 0);
}

describe('ST02 secrets', () => {
  describe('tracked env files', () => {
    it('finds .env and its variants anywhere in the tree, in any casing', () => {
      const paths = [
        '.env',
        'apps/agent/.env',
        '.env.local',
        'services/x/.env.production',
        '.ENV',
        '.Env.Example',
        'config/app.env',
        'prod.ENV',
      ];

      expect(findTrackedEnvFiles(paths)).toEqual(paths);
    });

    it('allows .env.example and files that only look similar', () => {
      const paths = ['.env.example', 'apps/web/.env.example', 'docs/env.md', 'src/.envrc-notes.ts'];

      expect(findTrackedEnvFiles(paths)).toEqual([]);
    });

    it('the repo tracks no env file except .env.example', async () => {
      expect(findTrackedEnvFiles(await listTrackedFiles())).toEqual([]);
    });

    it('finds every .env.example at any depth', () => {
      const paths = ['.env.example', 'apps/agent/.env.example', 'README.md', '.env.example.md'];

      expect(findEnvExamples(paths)).toEqual(['.env.example', 'apps/agent/.env.example']);
    });
  });

  describe('.env.example placeholders', () => {
    it.each([
      ['an empty value', 'AGENT_TOKEN='],
      ['change-me', 'AGENT_TOKEN=change-me'],
      ['change-me with a suffix', 'SESSIONS_DB_PASSWORD=change-me-sessions-db'],
      ['the placeholder npm run setup replaces', 'AGENT_TOKEN=change-me-run-npm-run-setup'],
      [
        'a suffix at the length limit',
        `AGENT_TOKEN=change-me-${'a'.repeat(MAX_PLACEHOLDER_SUFFIX - 1)}`,
      ],
      ['a quoted placeholder', 'AGENT_TOKEN="change-me"'],
      ['an exported placeholder', 'export AGENT_TOKEN=change-me'],
      ['a comment', '# AGENT_TOKEN is generated by npm run setup'],
      ['a blank line', '   '],
    ])('accepts %s', (_name, line) => {
      expect(findNonPlaceholderValues(line)).toEqual([]);
    });

    it.each([
      ['a token', 'AGENT_TOKEN=not-a-real-token'],
      ['a non-secret default', 'LOG_LEVEL=info'],
      ['a quoted value', "DB_PASSWORD='not-a-real-password'"],
      ['change-me used as a prefix', 'DB_PASSWORD=change-meXYZ'],
      ['a value with a trailing comment', 'DB_PASSWORD=change-me # not-a-real-password'],
      ['a hex secret behind the prefix', `AGENT_TOKEN=change-me-${FAKE_HEX_SECRET}`],
      ['a suffix with digits', 'AGENT_TOKEN=change-me-v2'],
      [
        'a suffix over the length limit',
        `AGENT_TOKEN=change-me-${'a'.repeat(MAX_PLACEHOLDER_SUFFIX)}`,
      ],
    ])('rejects %s', (_name, line) => {
      expect(findNonPlaceholderValues(line)).toEqual([
        expect.objectContaining({
          line: 1,
          reason: expect.not.stringMatching(/not-a-real|ab12/u),
        }),
      ]);
    });

    it('rejects lines that are not KEY=value entries', () => {
      expect(findNonPlaceholderValues('AGENT_TOKEN\nlower_case=change-me')).toEqual([
        { line: 1, key: undefined, reason: 'is not a KEY=value entry' },
        { line: 2, key: undefined, reason: 'is not a KEY=value entry' },
      ]);
    });

    it('reports the line number of each violation', () => {
      const content = '# header\nA=change-me\r\nB=secret\n\nC=other\n';

      expect(findNonPlaceholderValues(content).map(({ line, key }) => ({ line, key }))).toEqual([
        { line: 3, key: 'B' },
        { line: 5, key: 'C' },
      ]);
    });

    it('every tracked .env.example contains only placeholders', async () => {
      const examples = findEnvExamples(await listTrackedFiles());
      const contents = await Promise.all(
        examples.map(async (path) => ({
          path,
          violations: findNonPlaceholderValues(await readFile(join(REPO_ROOT, path), 'utf8')),
        })),
      );

      expect(contents.filter(({ violations }) => violations.length > 0)).toEqual([]);
    });
  });
});
