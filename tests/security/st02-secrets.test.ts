import { execFile } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

import { describe, expect, it } from 'vitest';
import { z } from 'zod';

import { findNonPlaceholderValues, findTrackedEnvFiles } from './lib/secrets-policy.js';

const run = promisify(execFile);
const REPO_ROOT = fileURLToPath(new URL('../../', import.meta.url));
const ENV_EXAMPLE = fileURLToPath(new URL('../../.env.example', import.meta.url));
const FsError = z.object({ code: z.string().optional() });

async function listTrackedFiles(): Promise<readonly string[]> {
  const { stdout } = await run('git', ['ls-files', '-z'], { cwd: REPO_ROOT });
  return stdout.split('\0').filter((path) => path.length > 0);
}

async function readIfPresent(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, 'utf8');
  } catch (error: unknown) {
    if (FsError.parse(error).code === 'ENOENT') {
      return undefined;
    }
    throw error;
  }
}

describe('ST02 secrets', () => {
  describe('tracked env files', () => {
    it('finds .env and its variants anywhere in the tree', () => {
      const paths = ['.env', 'apps/agent/.env', '.env.local', 'services/x/.env.production'];

      expect(findTrackedEnvFiles(paths)).toEqual(paths);
    });

    it('allows .env.example and files that only look similar', () => {
      const paths = ['.env.example', 'apps/web/.env.example', 'docs/env.md', 'src/.envrc-notes.ts'];

      expect(findTrackedEnvFiles(paths)).toEqual([]);
    });

    it('the repo tracks no env file except .env.example', async () => {
      expect(findTrackedEnvFiles(await listTrackedFiles())).toEqual([]);
    });
  });

  describe('.env.example placeholders', () => {
    it.each([
      ['an empty value', 'AGENT_TOKEN='],
      ['change-me', 'AGENT_TOKEN=change-me'],
      ['change-me with a suffix', 'SESSIONS_DB_PASSWORD=change-me-sessions-db'],
      ['a quoted placeholder', 'AGENT_TOKEN="change-me"'],
      ['an exported placeholder', 'export AGENT_TOKEN=change-me'],
      ['a comment', '# AGENT_TOKEN is generated by npm run setup'],
      ['a blank line', '   '],
    ])('accepts %s', (_name, line) => {
      expect(findNonPlaceholderValues(line)).toEqual([]);
    });

    it.each([
      ['a random token', 'AGENT_TOKEN=3f9a1c0b7d2e4f6a8b9c0d1e2f3a4b5c'],
      ['a non-secret default', 'LOG_LEVEL=info'],
      ['a quoted value', "DB_PASSWORD='hunter2'"],
      ['change-me used as a prefix', 'DB_PASSWORD=change-meXYZ'],
      ['a value with a trailing comment', 'DB_PASSWORD=change-me # real: hunter2'],
    ])('rejects %s', (_name, line) => {
      expect(findNonPlaceholderValues(line)).toEqual([
        expect.objectContaining({ line: 1, reason: expect.not.stringContaining('hunter2') }),
      ]);
    });

    it('rejects lines that are not KEY=value entries', () => {
      expect(findNonPlaceholderValues('AGENT_TOKEN\nlower_case=change-me')).toEqual([
        { line: 1, key: undefined, reason: 'is not a KEY=value entry' },
        { line: 2, key: undefined, reason: 'is not a KEY=value entry' },
      ]);
    });

    it('reports the line number of each violation', () => {
      const content = '# header\nA=change-me\r\nB=secret\n\nC=other\n';

      expect(findNonPlaceholderValues(content).map(({ line, key }) => ({ line, key }))).toEqual([
        { line: 3, key: 'B' },
        { line: 5, key: 'C' },
      ]);
    });

    it('the repo .env.example contains only placeholders', async ({ skip }) => {
      const content = await readIfPresent(ENV_EXAMPLE);
      if (content === undefined) {
        return skip('.env.example does not exist yet; T02 adds it');
      }

      expect(findNonPlaceholderValues(content)).toEqual([]);
    });
  });
});
