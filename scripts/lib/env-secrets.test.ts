import { readFile } from 'node:fs/promises';

import { describe, expect, it } from 'vitest';

import { InvalidEnvFileError, parseEnv, planEnv, SECRETS } from './env-secrets.js';

/** Lengths of a 32-byte secret in each accepted encoding. */
const BASE64URL_LENGTH = 43;
const HEX_LENGTH = 64;
const MAX_VALUE_LENGTH = 256;
const MIN_PASSWORD_LENGTH = 32;
const COUNTER_DIGITS = 3;

const VALID_SECRET = 'A'.repeat(BASE64URL_LENGTH);
const VALID_HEX_TOKEN = 'ab'.repeat(HEX_LENGTH / 2);

/** A generator that returns a distinct, valid value per call. */
function counter(): () => string {
  let next = 0;
  return () => {
    next += 1;
    return `${String(next).padStart(COUNTER_DIGITS, '0')}${'x'.repeat(BASE64URL_LENGTH - COUNTER_DIGITS)}`;
  };
}

function fullEnv(): string {
  return SECRETS.map(({ key }) => `${key}=${VALID_SECRET}\n`).join('');
}

function invalidProblems(action: () => unknown): readonly string[] {
  try {
    action();
  } catch (error: unknown) {
    if (error instanceof InvalidEnvFileError) {
      return error.problems;
    }
    throw error;
  }
  throw new Error('expected InvalidEnvFileError');
}

describe('SECRETS', () => {
  it('holds the superuser, one password per service role and the agent token', () => {
    expect(SECRETS.map(({ key }) => key)).toEqual([
      'POSTGRES_PASSWORD',
      'SESSIONS_DB_PASSWORD',
      'REPORTS_DB_PASSWORD',
      'GOALS_DB_PASSWORD',
      'BATTERY_DB_PASSWORD',
      'SYSTEM_DB_PASSWORD',
      'FOCUS_DB_PASSWORD',
      'GATEWAY_DB_PASSWORD',
      'AGENT_TOKEN',
    ]);
  });

  it('matches the keys listed in .env.example', async () => {
    const example = await readFile(new URL('../../.env.example', import.meta.url), 'utf8');

    expect(parseEnv(example).map(({ key }) => key)).toEqual(SECRETS.map(({ key }) => key));
  });
});

describe('parseEnv', () => {
  it('reads KEY=VALUE lines and skips blank lines and comments', () => {
    expect(parseEnv('# comment\n\nFOO=bar\r\nEMPTY=\n  # indented comment\n')).toEqual([
      { key: 'FOO', value: 'bar' },
      { key: 'EMPTY', value: '' },
    ]);
  });

  it('keeps "=" inside the value', () => {
    expect(parseEnv('URL=postgres://a?b=c\n')).toEqual([{ key: 'URL', value: 'postgres://a?b=c' }]);
  });

  it.each([
    ['a line without "="', 'NOT_AN_ASSIGNMENT\n'],
    ['a lower case key', 'foo=bar\n'],
    ['a space around "="', 'FOO = bar\n'],
    ['an export prefix', 'export FOO=bar\n'],
  ])('rejects %s', (_name, content) => {
    expect(invalidProblems(() => parseEnv(content))).toEqual([
      'line 1: expected KEY=VALUE with an upper case key',
    ]);
  });

  it('rejects a key defined twice, naming the line', () => {
    expect(invalidProblems(() => parseEnv('FOO=a\nFOO=b\n'))).toEqual([
      'line 2: FOO is defined twice',
    ]);
  });

  it('rejects an oversized value', () => {
    expect(() => parseEnv(`FOO=${'x'.repeat(MAX_VALUE_LENGTH + 1)}\n`)).toThrow(
      InvalidEnvFileError,
    );
  });
});

describe('planEnv', () => {
  it('creates every secret when there is no file', () => {
    const plan = planEnv(undefined, counter());

    expect(plan.added).toEqual(SECRETS.map(({ key }) => key));
    expect(plan.content.startsWith('# Generated by `npm run setup`. Never commit.\n')).toBe(true);
    expect(parseEnv(plan.content)).toHaveLength(SECRETS.length);
  });

  it('gives every secret its own value', () => {
    const plan = planEnv(undefined, counter());
    const values = parseEnv(plan.content).map(({ value }) => value);

    expect(new Set(values).size).toBe(SECRETS.length);
  });

  it('changes nothing when every secret is present', () => {
    const existing = `# mine\n${fullEnv()}OTHER=kept\n`;

    expect(planEnv(existing, counter())).toEqual({ content: existing, added: [] });
  });

  it('keeps existing values and appends only the missing secrets', () => {
    const existing = `AGENT_TOKEN=${VALID_HEX_TOKEN}\nOTHER=kept`;

    const plan = planEnv(existing, counter());

    expect(plan.added).not.toContain('AGENT_TOKEN');
    expect(plan.added).toHaveLength(SECRETS.length - 1);
    expect(plan.content.startsWith(`${existing}\n# Postgres superuser`)).toBe(true);
    expect(parseEnv(plan.content)).toContainEqual({ key: 'AGENT_TOKEN', value: VALID_HEX_TOKEN });
  });

  it('is idempotent: planning its own output adds nothing', () => {
    const first = planEnv(undefined, counter());

    expect(planEnv(first.content, counter())).toEqual({ content: first.content, added: [] });
  });

  it.each([
    ['a placeholder password', 'POSTGRES_PASSWORD=change-me\n', 'POSTGRES_PASSWORD'],
    [
      'a password with unsafe characters',
      `FOCUS_DB_PASSWORD=${'a'.repeat(BASE64URL_LENGTH)}@\n`,
      'FOCUS',
    ],
    ['a short agent token', 'AGENT_TOKEN=abc\n', 'AGENT_TOKEN must be 32 bytes'],
    ['a 63-character hex token', `AGENT_TOKEN=${'a'.repeat(HEX_LENGTH - 1)}\n`, 'AGENT_TOKEN'],
  ])('refuses %s instead of replacing it', (_name, existing, expected) => {
    const problems = invalidProblems(() => planEnv(existing, counter()));

    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain(expected);
  });

  it('never puts the rejected value in the error', () => {
    const secret = 'not-quite-long-enough-secret';

    expect(invalidProblems(() => planEnv(`POSTGRES_PASSWORD=${secret}\n`, counter()))).not.toEqual(
      expect.arrayContaining([expect.stringContaining(secret)]),
    );
  });

  it('accepts a long hand-chosen password', () => {
    const existing = `POSTGRES_PASSWORD=${'Zz9_-'.padEnd(MIN_PASSWORD_LENGTH, 'k')}\n`;

    expect(planEnv(existing, counter()).content.startsWith(existing)).toBe(true);
  });
});
